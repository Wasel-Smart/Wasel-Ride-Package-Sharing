-- Hash package hand-off verification codes at rest.
--
-- The original migration stored codes as plain text because the edge runtime
-- lacked a convenient crypto path. pgcrypto (bundled in every Supabase project)
-- lets us store codes as SHA-256 digests so a full DB read or a pg_dump cannot
-- expose live secrets.
--
-- Verification flow AFTER this migration:
--   1. Edge function generates a 6-digit code (crypto.randomInt on Deno side).
--   2. Edge function hashes it: SELECT encode(digest('123456', 'sha256'), 'hex')
--      and stores the hex string in pickup_verification_code / delivery_verification_code.
--   3. Edge function sends the plain code to the sender/receiver (SMS / push).
--   4. Verify endpoint receives the user-entered code, hashes it the same way,
--      and compares to the column value.
--
-- Data migration: null out existing plain-text codes -- they are either already
-- used (column verified = true) or orphaned. We do NOT hash them because we
-- don't know if they have already been consumed or are still awaiting use.
-- For in-flight packages (pickup_verified = false), operators must re-generate
-- codes via the admin panel after this migration runs.

BEGIN;

-- Enable pgcrypto if not already present (safe to run multiple times).
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Clear existing plain-text codes.
-- Codes for already-verified packages are no longer needed.
-- Codes for unverified packages must be regenerated by the edge function.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name='packages') THEN
    UPDATE public.packages
      SET pickup_verification_code    = NULL,
          delivery_verification_code  = NULL
      WHERE pickup_verification_code  IS NOT NULL
         OR delivery_verification_code IS NOT NULL;

    COMMENT ON COLUMN public.packages.pickup_verification_code IS
      'SHA-256 hex digest of the single-use pickup code. Store the hash; send the plain code to the user.';
    COMMENT ON COLUMN public.packages.delivery_verification_code IS
      'SHA-256 hex digest of the single-use delivery code. Store the hash; send the plain code to the user.';
  END IF;
END $$;

COMMIT;
